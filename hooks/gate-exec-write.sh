#!/usr/bin/env bash
# PreToolUse gate for the PostHog MCP `exec` tool.
#
# The PostHog MCP exposes a single `exec` tool that dispatches subcommands like
# `tools | search | info | schema | call <tool_name> [json]`. Once the user
# allow-lists `mcp__posthog__exec`, every subsequent `call` (including writes
# like `experiment-update`, `notebooks-destroy`, `cdp-functions-delete`) runs
# without a prompt. This hook re-introduces a prompt for write `call`s by
# returning `permissionDecision: "ask"`.
#
# Read-only PostHog tools and non-`call` exec verbs are left alone — the hook
# exits 0 so normal permission flow applies. A tool is read-only only when
# `hooks/read-tools.txt` lists it (every registry tool with readOnlyHint=true,
# regenerated by scripts/generate-read-tools.sh); every other `call` counts as
# a write, so tools added after the list was generated still reach the gate.
# Third-party tools proxied through the MCP gateway (`<server>__<tool>`) are
# left alone too.
#
# By default the prompt fires only for a curated "sensitive" subset of write
# tools — feature-flag writes and any delete/destroy — rather than every write.
# Three env vars tune this (all matched against the PostHog tool name):
#
#   POSTHOG_MCP_EXEC_GATE_DISABLE  — set to a non-empty value other than `0` (e.g.
#       `1`) to turn the gate off entirely, connection calls included; `0` leaves
#       the gate active. Useful for remote devboxes and Claude Cloud runs where the
#       prompt can't be answered. Example:
#
#           export POSTHOG_MCP_EXEC_GATE_DISABLE=1
#
#   POSTHOG_MCP_EXEC_GATE_DENY     — comma-separated bash globs selecting which
#       write tools prompt. Overrides the built-in default set. Use `*` to
#       prompt on every write (the previous behaviour). Tools on
#       `hooks/read-tools.txt` never prompt, whatever DENY says. Example:
#
#           export POSTHOG_MCP_EXEC_GATE_DENY="*feature-flag*,*-delete"
#
#   POSTHOG_MCP_EXEC_GATE_ALLOW    — comma-separated bash globs that opt specific
#       write tools out of the prompt. Applied on top of the deny set (allow
#       wins). Example:
#
#           export POSTHOG_MCP_EXEC_GATE_ALLOW="llma-skill-*,annotation-create"
#
# Exceptions: `posthog-connection-call` and `posthog-connection-forward` prompt
# whatever ALLOW and DENY say (only DISABLE or bypass mode silences them), and
# so does an exec input with more than one `command` field or a command the
# regex below can't check. Outside fail-closed mode, inputs that name no `call`
# (a missing or null `command`, a non-`call` verb, a payload whose `tool_name`
# can't be read) exit 0 silently.
#
# The gate stays silent for everything when the PreToolUse input reports
# `permission_mode` as `bypassPermissions` (a field Claude Code documents at
# https://code.claude.com/docs/en/hooks, "Common input fields"). Only the
# top-level field counts, and only up to the size cap: see `top_level_bypass`.
#
# Pure bash; no jq or other third-party tools required. Relies on the fact
# that PostHog tool names are kebab-case alphanumerics, so a narrow regex on
# the raw JSON payload is safe.

# `--fail-closed` is for hooks/codex-gate-exec-write.sh, which approves every
# call this script passes silently. In that mode the script passes only known
# reads (exec's read-only verbs and `call`s of tools on the read list), asks for
# everything else whatever the POSTHOG_MCP_EXEC_GATE_* variables say, and lets
# runtime failures exit non-zero, so the caller can tell a pass from a crash.
fail_closed=0
[[ "${1:-}" == --fail-closed ]] && fail_closed=1

# Otherwise fail open — this gate must never break a Claude Code tool call.
#
# The "ask" decision is delivered entirely through the stdout JSON below; the
# exit code is never used to signal it. So we force every exit path to 0 via an
# EXIT trap. Any unexpected runtime failure — an unbound variable under `set -u`,
# a failed builtin, an unusually old bash — then falls through to normal
# permission flow instead of surfacing as a hook error. Crucially, it can never
# exit 2, which Claude Code interprets as a hard *block* of the tool call.
#
# The one failure a trap can't catch is a parse-time syntax error (the trap
# isn't installed yet); `tests/test_gate_exec_write.sh` guards that with `bash -n`.
(( fail_closed )) || trap 'exit 0' EXIT

set -u

# Prompts with reason $1 and exits. The reason is interpolated into JSON
# unescaped, so callers pass fixed text or a [a-zA-Z0-9_-]+ tool name.
ask() {
    printf '{"hookSpecificOutput":{"hookEventName":"PreToolUse","permissionDecision":"ask","permissionDecisionReason":"%s"}}' "$1"
    exit 0
}

# Succeeds only when the input has exactly one top-level `permission_mode` member set to `bypassPermissions`.
# The input is split on `"` once, so the walk is linear. Only depth-1 keys count; a `permission_mode` in
# `tool_input` is ignored. Escaped quotes stay inside strings (RFC 8259 section 7). Malformed input (trailing
# text, bad escapes, mismatched brackets, nesting past 64 levels, a repeated key) fails.
#
# Size caps fail closed (the call prompts and the walk never runs): over `max_pieces` (20,000) pieces,
# over `max_opens` (1,000) non-root outside opens, or over `max_bytes` (131,072 bytes, 128 KB). A piece
# ending in 64 or more backslashes also fails.
top_level_bypass() {
    [[ "$input" == *'"permission_mode"'* ]] || return 1
    # The walk compares raw text and never decodes a JSON escape, so it can succeed
    # only when the literal bypassPermissions is in the input. A \u-escaped spelling
    # fails here and keeps the prompt.
    [[ "$input" == *bypassPermissions* ]] || return 1
    # A backslash must start a JSON escape: \" \\ \/ \b \f \n \r \t or \uXXXX. The left
    # anchor takes the whole backslash run, so an even run (\\) passes and \q fails. A
    # regex that does not compile (status 2) asks too.
    local esc_re='(^|[^\\])(\\\\)*\\([^"\\/bfnrtu]|u[0-9a-fA-F]{0,3}([^0-9a-fA-F]|$))' esc_rc=0
    [[ "$input" =~ $esc_re ]]; esc_rc=$?
    if (( esc_rc != 1 )); then return 1; fi
    # Depth above this many open brackets fails: the walk asks rather than tracking it.
    local max_depth=64
    local -a p
    local max_pieces=20000 max_opens=1000 max_bytes=131072
    local x w c pre wl off ch tl t tn j=0 k=0 n modes=0 value_ok=0 outside_opens=0
    # String state: inside a string, the stack depth where it opened, how many pieces it
    # spans so far, and whether any of them holds \u.
    local inside=0 sdepth=0 span=0 span_u=0
    # A key string just closed; the next outside piece decides whether it is a key.
    local pend=0 pend_u=0 pend_mode=0
    # After `"permission_mode":`, 1 expects the value and 2 means it matched.
    local value_stage=0
    # Brackets open outside strings, innermost last. The object's `{` is the first one.
    local stk='' top want
    # LC_ALL=C is set above, so ${#input} counts bytes.
    if (( ${#input} > max_bytes )); then return 1; fi
    IFS='"' read -ra p -d '' <<< "$input"
    n=${#p[@]}
    if (( n > max_pieces )); then return 1; fi
    for x in "${p[@]}"; do
        k=$(( k + 1 ))
        if (( inside )); then
            # Content piece. The last piece can never close a string.
            (( k < n )) || return 1
            span=$(( span + 1 ))
            [[ "$x" == *'\u'* ]] && span_u=1
            if (( value_stage == 1 )); then
                if [[ "$x" == bypassPermissions ]]; then value_stage=2; else value_stage=0; fi
            fi
            # Closed when the quote follows an even run of backslashes. Only the last 64
            # characters are counted, so the time stays bounded; a run of 64 or more fails.
            if (( ${#x} > 64 )); then tl=${x:${#x}-64}; else tl=$x; fi
            t="${tl##*[!\\]}"
            if (( ${#t} == 64 )); then return 1; fi
            if (( ${#t} % 2 == 0 )); then
                inside=0
                if (( sdepth == 1 )); then
                    pend=1; pend_u=$span_u; pend_mode=0
                    if (( span == 1 )) && [[ "$x" == permission_mode ]]; then pend_mode=1; fi
                fi
            fi
        else
            # Outside piece. Settle the value check, then the key closed just before it.
            if (( value_stage == 2 )); then
                [[ "$x" =~ ^[[:space:]]*[,}] ]] && value_ok=1
                value_stage=0
            fi
            if (( pend )); then
                if [[ "$x" =~ ^[[:space:]]*: ]]; then
                    # A top-level key written with \u might still be permission_mode (RFC 8259 section 7): ask.
                    (( pend_u )) && return 1
                    if (( pend_mode )); then
                        modes=$(( modes + 1 ))
                        [[ "$x" =~ ^[[:space:]]*:[[:space:]]*$ ]] && value_stage=1
                    fi
                fi
                pend=0
            fi
            w="$x"
            if (( k == 1 )); then
                # The object opens in the first piece: only whitespace may come before its `{`.
                [[ "$x" =~ ^[[:space:]]*\{ ]] || return 1
                w="${x#*\{}"
                stk='{'
            fi
            # Brackets are read from 256-character chunks: a substring copies the whole piece,
            # so one bracket at a time from the full piece would take quadratic time in bash 3.2.
            wl=${#w}
            for (( off = 0; off < wl; off += 256 )); do
                c="${w:off:256}"
                while [[ "$c" == *[\{\[\}\]]* ]]; do
                    pre="${c%%[\{\[\}\]]*}"
                    c="${c:${#pre}}"
                    ch="${c:0:1}"
                    c="${c:1}"
                    case "$ch" in
                        '{'|'[')
                            # An opener after the object closed, or nesting past the cap, fails.
                            if (( ${#stk} == 0 || ${#stk} >= max_depth )); then return 1; fi
                            stk="$stk$ch"
                            outside_opens=$(( outside_opens + 1 ))
                            if (( outside_opens > max_opens )); then return 1; fi
                            ;;
                        *)
                            # A closer must match the innermost open bracket, and none may follow the
                            # object's own `}`.
                            if (( ${#stk} == 0 )); then return 1; fi
                            top="${stk:${#stk}-1:1}"
                            if [[ "$ch" == '}' ]]; then want='{'; else want='['; fi
                            if [[ "$top" != "$want" ]]; then return 1; fi
                            stk="${stk:0:${#stk}-1}"
                            ;;
                    esac
                done
            done
            if (( k < n )); then
                inside=1; sdepth=${#stk}; span=0; span_u=0
            fi
        fi
    done
    (( modes == 1 && value_ok )) || return 1
    # Every opener is closed, so the object's `}` was the last bracket.
    [[ -z "$stk" ]] || return 1
    # The object's `}` must be the last non-whitespace character; only the last 4097 characters are read.
    tl="$input"
    if (( ${#tl} > 4097 )); then tl="${tl:${#tl}-4097}"; fi
    tn=${#tl}
    while (( j < tn )); do
        ch="${tl:tn-1-j:1}"
        case "$ch" in ' '|$'\t'|$'\r'|$'\n') j=$(( j + 1 )) ;; *) break ;; esac
    done
    (( j < tn )) && [[ "${tl:tn-1-j:1}" == '}' ]]
}

# Passes in normal mode; asks in fail-closed mode.
not_a_known_read() {
    (( fail_closed )) || exit 0
    ask "The PostHog exec command is not a known read — approve to run."
}

# Codex compatibility: Codex's PreToolUse protocol does not support
# `permissionDecision: "ask"` (it is parsed then rejected as unsupported), so
# Codex runs this script through hooks/codex-gate-exec-write.sh instead. Skip the
# gate if a Codex build loads it from hooks/hooks.json directly, detected via its
# native PLUGIN_ROOT env var — Claude Code only ever sets CLAUDE_PLUGIN_ROOT,
# never PLUGIN_ROOT. See https://developers.openai.com/codex/hooks
if [[ -n "${PLUGIN_ROOT:-}" ]] && (( ! fail_closed )); then
    exit 0
fi

# Full opt-out — turn the gate off entirely. Set to any non-empty value other
# than `0`. Lets remote devboxes and Claude Cloud runs, where no one can answer
# the prompt, run write `call`s without interruption. In fail-closed mode it
# would approve every write, so it is ignored there.
if [[ -n "${POSTHOG_MCP_EXEC_GATE_DISABLE:-}" && "${POSTHOG_MCP_EXEC_GATE_DISABLE}" != "0" ]] && (( ! fail_closed )); then
    exit 0
fi

input="$(cat)"

# Default set of write tools that prompt. Comma-separated bash globs, grounded in
# the live PostHog MCP tool registry. Covers the genuinely sensitive surface:
#
#   *feature-flag*  — feature-flag rollout writes: create-feature-flag,
#                     update-feature-flag, delete-feature-flag,
#                     feature-flags-bulk-{delete,update-tags}-create,
#                     feature-flags-copy-flags-create
#   *delete*        — any deletion: insight-delete, dashboard-delete,
#                     cdp-functions-delete, persons-bulk-delete,
#                     external-data-schemas-delete-data, session-recording-delete, …
#   *destroy*       — any destroy: notebooks-destroy, accounts-destroy,
#                     experiment-saved-metrics-destroy, agent-applications-destroy, …
#   experiment-launch / experiment-ship-variant / experiment-reset
#                   — start exposing users / roll a variant to everyone / wipe results
#   survey-launch   — start showing a survey to real users
#   workflows-enable — activate a user-facing automation
#
# Deliberately silent by default (lower blast radius / easily reverted): routine
# create & update (insight, dashboard, annotation, cohort, alert, skill, …),
# experiment-pause/resume/end, survey-stop, persons-property-set,
# error-tracking-issues-merge/split. Add any of these via
# POSTHOG_MCP_EXEC_GATE_DENY, which overrides this set wholesale; use
# POSTHOG_MCP_EXEC_GATE_DENY="*" to restore prompting on every write.
DEFAULT_DENY='*feature-flag*,*delete*,*destroy*,experiment-launch,experiment-ship-variant,experiment-reset,survey-launch,workflows-enable'

# Extract `tool_name` — simple identifier, no escaping inside the value.
tool_name=""
if [[ "$input" =~ \"tool_name\"[[:space:]]*:[[:space:]]*\"([^\"]+)\" ]]; then
    tool_name="${BASH_REMATCH[1]}"
fi

# Match any MCP tool whose name ends in `__exec` regardless of plugin/server
# namespacing (bare `mcp__posthog__exec` or plugin-prefixed variants like
# `mcp__posthog_posthog__exec`).
[[ "$tool_name" =~ __exec$ ]] || not_a_known_read

# Extract the PostHog tool name from `"command":"call [--flag ...] <tool>..."`.
# The server trims the command with JavaScript's trim() and skips any number of
# `--json`/`--confirm` flags, so whitespace may surround `call` and each flag:
# ASCII, a JSON escape like `\n` or `\u000b`, or raw UTF-8 Unicode whitespace,
# which is matched as any non-ASCII byte under the C locale (extra prompts only).
# Tool names are kebab-case [a-zA-Z0-9_-]+ so the regex stops cleanly at the
# first space or escaped quote without needing to parse the trailing JSON.
#
# The regex only compiles under LC_ALL=C: raw bytes \x80-\xff are invalid in a
# UTF-8 locale, where `=~` returns 2 and nothing would ever match. A match
# status of 2 therefore prompts instead of passing.
LC_ALL=C
ws='([[:space:]]|\\[nrtf]|\\u000[bB]|['$'\x80''-'$'\xff'']'')'
call_re="\"command\"[[:space:]]*:[[:space:]]*\"${ws}*call${ws}+((--[a-zA-Z-]+${ws}+)*)([a-zA-Z0-9_-]+)"

# Bypass mode: the user chose to run without prompts (issue #246), so none of the
# prompts below apply. Not in fail-closed mode: hooks/codex-gate-exec-write.sh:20-23
# reads a silent gate as an approval.
if (( ! fail_closed )) && top_level_bypass; then
    exit 0
fi

# The regex reads the first `command` key, so a second one (say, nested in an
# extra object) could hide the real command behind a decoy. Quotes inside the
# command string are escaped, so a body like {"command":…} doesn't count.
if [[ "$input" =~ \"command\"[[:space:]]*:.*\"command\"[[:space:]]*: ]]; then
    ask "The PostHog exec input has more than one command — approve to run."
fi

posthog_tool=""
[[ "$input" =~ $call_re ]]
case $? in
    0) posthog_tool="${BASH_REMATCH[${#BASH_REMATCH[@]}-1]}" ;;
    2) ask "The PostHog exec command could not be checked — approve to run." ;;
esac

# Without a `call`, fail-closed mode passes only exec's read-only verbs, which
# the server reads up to the first space.
if [[ -z "$posthog_tool" ]] && (( fail_closed )); then
    read_verb_re="\"command\"[[:space:]]*:[[:space:]]*\"${ws}*(help|learn|tools|search|info|schema)( |\")"
    [[ "$input" =~ $read_verb_re ]] || not_a_known_read
fi
[[ -n "$posthog_tool" ]] || exit 0

# These run any tool, deletes included, in another project, so they always prompt.
if [[ "$posthog_tool" == posthog-connection-call || "$posthog_tool" == posthog-connection-forward ]]; then
    ask "\`$posthog_tool\` runs a tool in another PostHog project — approve to run."
fi

# Third-party tools reached through the MCP gateway are named `<server>__<tool>`
# (PostHog tool names never contain `__`) and follow their server's own policy.
[[ "$posthog_tool" == *__* ]] && not_a_known_read

read_tools_file="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)/read-tools.txt"
if [[ -r "$read_tools_file" ]]; then
    read_tools=$'\n'"$(<"$read_tools_file")"$'\n'
    [[ "$read_tools" == *$'\n'"$posthog_tool"$'\n'* ]] && exit 0
fi
if (( fail_closed )); then
    not_a_known_read
fi

# Match comma-separated bash globs in $2 against the PostHog tool name ($1).
# Whitespace around each pattern is trimmed; empty patterns are skipped.
# Returns 0 on the first match, 1 if none match.
matches_any_glob() {
    local tool="$1" patterns="$2" _pat
    local -a _list
    IFS=',' read -ra _list <<< "$patterns"
    for _pat in "${_list[@]}"; do
        _pat="${_pat#"${_pat%%[![:space:]]*}"}"
        _pat="${_pat%"${_pat##*[![:space:]]}"}"
        [[ -n "$_pat" && "$tool" == $_pat ]] && return 0
    done
    return 1
}

shopt -s nocasematch

# Allowlist wins — skip the prompt for tools matching any glob in
# POSTHOG_MCP_EXEC_GATE_ALLOW. Patterns use bash glob syntax (`*`, `?`).
if [[ -n "${POSTHOG_MCP_EXEC_GATE_ALLOW:-}" ]]; then
    matches_any_glob "$posthog_tool" "$POSTHOG_MCP_EXEC_GATE_ALLOW" && exit 0
fi

# Denylist selects which writes actually prompt. POSTHOG_MCP_EXEC_GATE_DENY
# overrides the built-in default set; an empty/unset value falls back to it.
deny_patterns="${POSTHOG_MCP_EXEC_GATE_DENY:-}"
[[ -n "$deny_patterns" ]] || deny_patterns="$DEFAULT_DENY"
matches_any_glob "$posthog_tool" "$deny_patterns" || exit 0

# `posthog_tool` is restricted to [a-zA-Z0-9_-]+ by the regex above, so
# interpolating it into the JSON response is safe — no characters that
# would need escaping for JSON or printf.
ask "\`$posthog_tool\` modifies PostHog data — approve to run."
