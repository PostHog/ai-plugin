#!/usr/bin/env bash
# Writes hooks/read-tools.txt: every PostHog MCP tool whose readOnlyHint is
# true, read from the two tool definition files on PostHog/posthog master. The
# exec write gate treats any tool not on this list as a write. Requires curl and jq.
set -euo pipefail

REGISTRY_BASE_URL="${REGISTRY_BASE_URL:-https://raw.githubusercontent.com/PostHog/posthog/master/services/mcp/schema}"
HERE="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
OUT="$HERE/../hooks/read-tools.txt"

tmp="$(mktemp)"
trap 'rm -f "$tmp"' EXIT

{
    echo "# Generated by scripts/generate-read-tools.sh from PostHog/posthog master. Do not edit by hand."
    {
        curl -fsSL --retry 2 --retry-delay 3 "$REGISTRY_BASE_URL/tool-definitions.json"
        curl -fsSL --retry 2 --retry-delay 3 "$REGISTRY_BASE_URL/generated-tool-definitions.json"
    } | jq -rs 'add | to_entries[] | select(.value.annotations.readOnlyHint == true) | .key' \
        | LC_ALL=C sort -u
} > "$tmp"

count="$(grep -c -v '^#' "$tmp" || true)"
# An empty list means the registry format changed, not that every tool became a write.
if (( count == 0 )); then
    echo "refusing to write $OUT: the registry has no read-only tools" >&2
    exit 1
fi
mv "$tmp" "$OUT"
trap - EXIT
echo "wrote $count read-only tools to $OUT"
