#!/usr/bin/env bash
# Writes hooks/read-tools.txt: every PostHog MCP tool whose readOnlyHint is
# true, read from the tool registry on PostHog/posthog master. The exec write
# gate treats any tool not on this list as a write. Requires curl and jq.
set -euo pipefail

REGISTRY_URL="${REGISTRY_URL:-https://raw.githubusercontent.com/PostHog/posthog/master/services/mcp/schema/tool-definitions-all.json}"
HERE="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
OUT="$HERE/../hooks/read-tools.txt"

tmp="$(mktemp)"
trap 'rm -f "$tmp"' EXIT

{
    echo "# Generated by scripts/generate-read-tools.sh from PostHog/posthog master. Do not edit by hand."
    curl -fsSL --retry 2 --retry-delay 3 "$REGISTRY_URL" \
        | jq -r 'to_entries[] | select(.value.annotations.readOnlyHint == true) | .key' \
        | LC_ALL=C sort -u
} > "$tmp"

# The sync PR auto-merges, so cap the daily change at 10% of the committed
# list. Additions are the dangerous direction, since each one stops gating a
# tool; removals only add prompts but are capped too, because accepting a
# collapsed list would make the addition cap refuse its recovery. To accept a
# larger change on purpose, delete the committed list and rerun.
if [[ -f "$OUT" ]]; then
    committed="$(grep -c -v '^#' "$OUT" || true)"
    added="$(LC_ALL=C comm -13 <(grep -v '^#' "$OUT") <(grep -v '^#' "$tmp") | wc -l)"
    removed="$(LC_ALL=C comm -23 <(grep -v '^#' "$OUT") <(grep -v '^#' "$tmp") | wc -l)"
    if (( added * 10 > committed || removed * 10 > committed )); then
        echo "refusing to write $OUT: +$added/-$removed read-only tools vs $committed committed is over 10%" >&2
        exit 1
    fi
fi
count="$(grep -c -v '^#' "$tmp" || true)"
mv "$tmp" "$OUT"
trap - EXIT
echo "wrote $count read-only tools to $OUT"
